import 'package:flutter_secure_storage/flutter_secure_storage.dart';

/// Almacén clave-valor cifrado (ADR-043 D5/D12: `flutter_secure_storage`, la única tecnología de almacenamiento
/// aprobada). Abstracto para poder probar los stores sin la plataforma.
abstract class SecureKeyValueStore {
  Future<String?> read(String key);
  Future<void> write(String key, String value);
  Future<void> delete(String key);
}

class FlutterSecureKeyValueStore implements SecureKeyValueStore {
  const FlutterSecureKeyValueStore([this._storage = const FlutterSecureStorage()]);

  final FlutterSecureStorage _storage;

  @override
  Future<String?> read(String key) => _storage.read(key: key);

  @override
  Future<void> write(String key, String value) => _storage.write(key: key, value: value);

  @override
  Future<void> delete(String key) => _storage.delete(key: key);
}
